// Core domain types for TripPilot. These mirror the Supabase schema
// (see supabase/migrations) and are shared by the local demo store.

export type TravelStyle =
  | "luxury"
  | "comfort"
  | "balanced"
  | "budget"
  | "backpacker"
  | "adventure";

export type Pace = "relaxed" | "balanced" | "packed";
export type TravelParty = "solo" | "couple" | "family" | "friends" | "business";
export type BudgetRange = "under-1k" | "1k-3k" | "3k-6k" | "6k-10k" | "10k-plus";
export type Accommodation =
  | "luxury-hotel"
  | "boutique-hotel"
  | "mid-range-hotel"
  | "apartment"
  | "hostel"
  | "resort";

export interface TravelPreferences {
  travel_style: TravelStyle;
  budget_range: BudgetRange;
  accommodation: Accommodation;
  food_preferences: string[];
  activities: string[];
  pace: Pace;
  travel_party: TravelParty;
  preferred_destinations: string[];
  accessibility_needs: string;
}

export interface NotificationPreferences {
  trip_reminders: boolean;
  itinerary_changes: boolean;
  product_updates: boolean;
}

export interface Profile {
  id: string;
  email: string | null;
  full_name: string | null;
  home_currency: string;
  onboarded: boolean;
  notifications: NotificationPreferences;
  created_at: string;
  updated_at: string;
}

export type TripStatus = "planning" | "upcoming" | "active" | "completed";

export interface Trip {
  id: string;
  user_id: string;
  name: string;
  destinations: string[];
  start_date: string; // YYYY-MM-DD
  end_date: string; // YYYY-MM-DD
  travelers: number;
  travel_party: TravelParty;
  budget: number;
  currency: string;
  budget_excludes_flights: boolean;
  pace: Pace;
  interests: string[];
  description: string;
  special_requests: string;
  cover_image: string | null;
  /** "ai" = generated by Claude, "demo" = sample content, "manual" = no generation yet */
  itinerary_source: "ai" | "demo" | "manual" | null;
  created_at: string;
  updated_at: string;
}

export type DaySlot = "morning" | "afternoon" | "evening";

export type ActivityCategory =
  | "sightseeing"
  | "museum"
  | "food"
  | "restaurant"
  | "nightlife"
  | "outdoors"
  | "shopping"
  | "wellness"
  | "experience"
  | "transport"
  | "accommodation"
  | "other";

export type ContentSource = "ai" | "demo" | "user";

export interface Activity {
  id: string;
  day_id: string;
  trip_id: string;
  name: string;
  description: string;
  category: ActivityCategory;
  is_restaurant: boolean;
  slot: DaySlot;
  suggested_time: string | null; // "HH:MM"
  duration_minutes: number | null;
  estimated_cost: number | null;
  address: string | null;
  latitude: number | null;
  longitude: number | null;
  booking_url: string | null;
  notes: string;
  completed: boolean;
  sort_order: number;
  source: ContentSource;
  /** True once the traveler edited it; AI regeneration must preserve it. */
  user_modified: boolean;
  created_at: string;
  updated_at: string;
}

export interface ItineraryDay {
  id: string;
  trip_id: string;
  day_number: number;
  date: string; // YYYY-MM-DD
  title: string;
  summary: string;
  city: string;
  morning_summary: string;
  afternoon_summary: string;
  evening_summary: string;
  transport_notes: string;
  notes: string;
  estimated_cost: number | null;
  source: ContentSource;
  created_at: string;
  updated_at: string;
  activities: Activity[];
}

export type BookingType =
  | "flight"
  | "hotel"
  | "restaurant"
  | "activity"
  | "transport"
  | "car_rental"
  | "other";

export interface BookingDocument {
  name: string;
  path: string; // storage path (Supabase) or data URL (demo)
  size: number;
  uploaded_at: string;
}

export interface Booking {
  id: string;
  trip_id: string;
  type: BookingType;
  name: string;
  confirmation_number: string;
  date: string | null;
  time: string | null;
  end_date: string | null;
  address: string;
  booking_url: string;
  cost: number | null;
  notes: string;
  documents: BookingDocument[];
  created_at: string;
  updated_at: string;
}

export type ExpenseCategory =
  | "accommodation"
  | "food"
  | "activities"
  | "transport"
  | "shopping"
  | "flights"
  | "other";

export interface Expense {
  id: string;
  trip_id: string;
  description: string;
  category: ExpenseCategory;
  amount: number;
  currency: string;
  date: string;
  is_planned: boolean;
  created_at: string;
  updated_at: string;
}

export interface SavedPlace {
  id: string;
  user_id: string;
  trip_id: string | null;
  name: string;
  city: string;
  category: ActivityCategory;
  notes: string;
  latitude: number | null;
  longitude: number | null;
  created_at: string;
}

export type ChatRole = "user" | "assistant";

export interface ChatMessage {
  id: string;
  trip_id: string;
  role: ChatRole;
  content: string;
  /** Proposed itinerary operations attached to an assistant reply. */
  proposal: ChangeProposal | null;
  /** "live" = Claude, "demo" = scripted demo response */
  mode: "live" | "demo" | null;
  created_at: string;
}

/** A snapshot of everything about a trip, used by the trip dashboard and AI. */
export interface TripBundle {
  trip: Trip;
  days: ItineraryDay[];
  bookings: Booking[];
  expenses: Expense[];
  messages: ChatMessage[];
  savedPlaces: SavedPlace[];
}

// ---------- AI change proposals (concierge) ----------

export interface ProposedActivity {
  name: string;
  description: string;
  category: ActivityCategory;
  is_restaurant: boolean;
  slot: DaySlot;
  suggested_time: string | null;
  duration_minutes: number | null;
  estimated_cost: number | null;
  address: string | null;
  latitude: number | null;
  longitude: number | null;
  booking_url: string | null;
  notes: string;
}

export type ChangeOperation =
  | { type: "remove_activity"; activity_id: string; reason: string; target_name?: string }
  | {
      type: "replace_activity";
      activity_id: string;
      target_name?: string;
      reason: string;
      activity: ProposedActivity;
    }
  | {
      type: "add_activity";
      day_number: number;
      reason: string;
      activity: ProposedActivity;
    };

export interface ChangeProposal {
  summary: string;
  operations: ChangeOperation[];
  status: "pending" | "applied" | "dismissed";
}
